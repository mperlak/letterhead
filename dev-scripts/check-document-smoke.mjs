#!/usr/bin/env node
// Smoke test for letterhead/scripts/check-document.mjs.
//
// Starts from one small clean document, then breaks it one way at a time and
// asserts the exit code and the rule id that fires. Also checks that
// warnings alone keep exit 0, that code samples are not read as prose, that
// the large-heading contrast floor applies, and the --json output shape.
//
// Usage: node dev-scripts/check-document-smoke.mjs
// Exit codes: 0 all assertions passed, 1 an assertion failed.

import { spawnSync } from 'node:child_process';
import { mkdtempSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SCRIPT = join(ROOT, 'letterhead', 'scripts', 'check-document.mjs');
const TMP = mkdtempSync(join(tmpdir(), 'check-document-smoke-'));

const CLEAN = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>Order sync plan</title>
<link rel="icon" href="data:image/svg+xml,%3Csvg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 1 1'/%3E">
<meta property="og:title" content="Order sync plan">
<meta property="og:description" content="How orders move between the two systems.">
<style>
:root { --background: oklch(0.99 0 0); --foreground: oklch(0.22 0 0); --muted: oklch(0.68 0 0); --brand: oklch(0.62 0.12 250); }
[data-theme="dark"] { --background: oklch(0.2 0 0); --foreground: oklch(0.93 0 0); }
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]):not([data-theme="dark"]) { --background: oklch(0.2 0 0); --foreground: oklch(0.93 0 0); }
  :root:not([data-theme="light"]) .logo { filter: invert(1); }
}
body { color: var(--foreground); background: var(--background); }
h1 { color: var(--brand); background: var(--background); }
.note { color: var(--foreground); background: var(--background); transition: opacity 120ms; }
</style>
</head>
<body>
<header>
<h1>Order sync plan</h1>
<dl class="meta"><dt>Status</dt><dd>Draft for comments</dd><dt>Owner</dt><dd>Ana Ruiz</dd><dt>Date</dt><dd>18 October 2026</dd></dl>
</header>
<h2 id="summary">Summary</h2>
<p class="note">Orders move every five minutes. <a href="#scope">Scope</a> is below.</p>
<pre><code>// TODO in a code sample is not a draft marker
render("{{name}}")</code></pre>
<h2 id="scope">Scope</h2>
<h3 id="in-scope">In scope</h3>
<p>Paid orders and refunds.</p>
<img src="data:image/gif;base64,R0lGODlhAQABAAAAACw=" alt="" width="1" height="1">
</body>
</html>
`;

function write(name, html) {
  const p = join(TMP, name);
  writeFileSync(p, html);
  return p;
}

function run(args) {
  const res = spawnSync(process.execPath, [SCRIPT, ...args], { encoding: 'utf8' });
  return { status: res.status, out: `${res.stdout}${res.stderr}` };
}

function swap(from, to) {
  if (!CLEAN.includes(from)) throw new Error(`smoke fixture does not contain: ${from}`);
  return CLEAN.replace(from, to);
}

let failures = 0;
function check(label, cond, detail) {
  if (cond) console.log(`  ok - ${label}`);
  else {
    console.log(`  FAIL - ${label}`);
    if (detail) console.log(detail.split('\n').map((l) => `      ${l}`).join('\n'));
    failures++;
  }
}

console.log('clean document');
{
  const r = run([write('clean.html', CLEAN)]);
  check('exits 0', r.status === 0, r.out);
  check('reports no findings at all', /0 error, 0 warning, 0 info/.test(r.out), r.out);
}

// One broken document per error rule.
const BROKEN = [
  ['lorem ipsum', 'doc/template-leftover', swap('Paid orders and refunds.', 'Lorem ipsum dolor sit amet.')],
  ['[your ...] bracket', 'doc/template-leftover', swap('Paid orders and refunds.', 'Signed, [your name].')],
  ['[Twoje ...] bracket', 'doc/template-leftover', swap('Paid orders and refunds.', 'Podpis: [Twoje imię].')],
  ['{{placeholder}}', 'doc/template-leftover', swap('Paid orders and refunds.', 'Dear {{client_name}},')],
  ['TODO in prose', 'doc/draft-marker', swap('Paid orders and refunds.', 'TODO: confirm refunds.')],
  ['FIXME in prose', 'doc/draft-marker', swap('Paid orders and refunds.', 'Refunds FIXME later.')],
  ['[TBD]', 'doc/draft-marker', swap('Paid orders and refunds.', 'Refund window [TBD].')],
  ['[WIP]', 'doc/draft-marker', swap('<h2 id="scope">Scope</h2>', '<h2 id="scope">Scope [WIP]</h2>')],
  ['[DRAFT]', 'doc/draft-marker', swap('Paid orders and refunds.', '[DRAFT] Paid orders.')],
  ['TKTK', 'doc/draft-marker', swap('Paid orders and refunds.', 'Refunds TKTK.')],
  ['"Generated by AI" footer', 'doc/ai-residue', swap('</body>', '<footer>Generated by AI.</footer></body>')],
  ['"generated with ChatGPT"', 'doc/ai-residue', swap('Paid orders and refunds.', 'Text generated with ChatGPT.')],
  ['【…】 citation', 'doc/ai-residue', swap('Paid orders and refunds.', 'Refunds take 5 days【4:2†source】.')],
  ['[cite: …] marker', 'doc/ai-residue', swap('Paid orders and refunds.', 'Refunds take 5 days [cite: 12].')],
  [':contentReference marker', 'doc/ai-residue', swap('Paid orders and refunds.', 'Refunds :contentReference[oaicite:3]{index=3}.')],
  ['no lang', 'doc/missing-lang', swap('<html lang="en">', '<html>')],
  ['empty lang', 'doc/missing-lang', swap('<html lang="en">', '<html lang="">')],
  ['no <title>', 'doc/title-missing', swap('<title>Order sync plan</title>', '')],
  ['empty <title>', 'doc/title-missing', swap('<title>Order sync plan</title>', '<title> </title>')],
  ['img without alt', 'doc/img-no-alt', swap(' alt="" width', ' width')],
  ['link without a name', 'doc/link-no-name', swap('<a href="#scope">Scope</a>', '<a href="#scope"></a>')],
  ['external script', 'doc/external-resource', swap('</head>', '<script src="https://cdn.jsdelivr.net/npm/mermaid@10/dist/mermaid.min.js"></script></head>')],
  ['external stylesheet import', 'doc/external-resource', swap('<style>', '<style>@import url("https://fonts.example.com/inter.css");')],
  ['dark media overrides explicit light', 'doc/dark-overrides-light', swap(':root:not([data-theme="light"]):not([data-theme="dark"]) {', ':root {')],
  ['unguarded rule in dark media', 'doc/dark-overrides-light', swap(':root:not([data-theme="light"]) .logo', '.logo')],
  ['low contrast body text', 'doc/low-contrast', swap('--foreground: oklch(0.22 0 0)', '--foreground: oklch(0.8 0 0)')],
  ['low contrast rule', 'doc/low-contrast', swap('.note { color: var(--foreground);', '.note { color: var(--muted);')],
  ['low contrast h1 below 3:1', 'doc/low-contrast', swap('--brand: oklch(0.62 0.12 250)', '--brand: oklch(0.85 0.06 250)')],
  ['h2 without id', 'doc/heading-no-id', swap('<h2 id="scope">', '<h2>')],
  ['duplicate heading id', 'doc/duplicate-id', swap('<h3 id="in-scope">', '<h3 id="scope">')],
];

console.log('one error rule at a time');
for (const [label, rule, html] of BROKEN) {
  const r = run([write(`${rule.replace('/', '-')}-${label.replace(/\W+/g, '-')}.html`, html)]);
  check(`${label} → exit 2, ${rule}`, r.status === 2 && r.out.includes(` error ${rule} `), r.out);
}

console.log('warnings and info do not fail');
{
  const warnOnly = swap('<link rel="icon"', '<link rel="preload"').replace('<h3 id="in-scope">In scope</h3>', '<h4>In scope</h4>');
  const r = run([write('warnings.html', warnOnly)]);
  check('missing favicon + skipped level → exit 0', r.status === 0, r.out);
  check('doc/no-favicon reported as warning', r.out.includes(' warning doc/no-favicon '), r.out);
  check('doc/heading-outline reported as warning', r.out.includes(' warning doc/heading-outline '), r.out);

  const moves = swap('transition: opacity 120ms', 'transition: all 120ms');
  const m = run([write('motion.html', moves)]);
  check('transition: all → warning doc/layout-animation, exit 0', m.status === 0 && m.out.includes(' warning doc/layout-animation '), m.out);

  const numbered = swap('<h2 id="summary">Summary</h2>', '<h2 id="summary"><span>01</span> Summary</h2>');
  const n = run([write('numbered.html', numbered)]);
  check('"01" section number → info doc/section-numbers, exit 0', n.status === 0 && n.out.includes(' info doc/section-numbers '), n.out);

  const LONG = 'verified · tmp/mcp-agent-usability-audit.md, 16.10.2026';
  const withBody = (html) => swap('<p>Paid orders and refunds.</p>', `<p>Paid orders and refunds.</p>${html}`);
  const lc = run([write('state-long.html', withBody(`<p><span class="state ok">${LONG}</span></p>`))]);
  check('a 50+ character .state → warning doc/state-long, exit 0', lc.status === 0 && lc.out.includes(' warning doc/state-long '), lc.out);
  const sc = run([write('state-short.html', withBody('<p><span class="state ok">passed</span> <span class="state warn">waiting for legal review</span></p>'))]);
  check('short .state chips (up to 24 characters) → no doc/state-long', sc.status === 0 && !sc.out.includes('doc/state-long'), sc.out);
  const led = run([write('state-ledger.html', withBody(`<dl class="status"><div><dt>Audit</dt><dd><span class="state ok">${LONG}</span></dd></div></dl>`))]);
  check('a long .state inside .status (styles wrap it as prose) is not flagged', !led.out.includes('doc/state-long'), led.out);

  const emoji = swap('<h2 id="summary">Summary</h2>', '<h2 id="summary">🚀 Summary</h2>');
  const e = run([write('emoji.html', emoji)]);
  check('emoji heading → info doc/emoji-heading, exit 0', e.status === 0 && e.out.includes(' info doc/emoji-heading '), e.out);
}

console.log('structure: date field, links, contents, flat page, SVG controls, lists');
{
  const has = (html, rule) => run([write(`${rule.replace('/', '-')}.html`, html)]).out.includes(rule);
  check('no date field → warning doc/meta-no-date', has(swap('<dt>Date</dt><dd>18 October 2026</dd>', ''), ' warning doc/meta-no-date '));
  check('a date in a value counts ("Last updated: 2026-10-18")', !has(swap('<dt>Date</dt><dd>18 October 2026</dd>', '<dt>Version</dt><dd>2026-10-18</dd>'), 'doc/meta-no-date'));
  check('link to a missing id → error doc/dead-anchor', has(swap('href="#scope"', 'href="#nowhere"'), ' error doc/dead-anchor '));
  const nav = (items) => `<nav class="contents"><ol>${items.map((i) => `<li><a href="#${i}">${i}</a></li>`).join('')}</ol></nav>`;
  check('one contents list skipping an h2 → doc/contents-incomplete', has(swap('</header>', `</header>${nav(['summary', 'summary', 'in-scope'])}`), 'doc/contents-incomplete'));
  check('two contents lists that differ → doc/contents-mismatch', has(swap('</header>', `</header>${nav(['summary', 'scope', 'in-scope'])}<details><summary>Go</summary><ol><li><a href="#summary">a</a></li><li><a href="#in-scope">b</a></li><li><a href="#summary">c</a></li></ol></details>`), 'doc/contents-mismatch'));
  check('more than 12 paragraphs straight in <body> → doc/flat-main', has(swap('<p>Paid orders and refunds.</p>', '<p>x</p>'.repeat(13)), 'doc/flat-main'));
  check('a focusable part in <svg role="img"> → error doc/svg-img-controls', has(swap('</body>', '<svg role="img" aria-label="d"><g tabindex="0" role="button"><rect/></g></svg></body>'), ' error doc/svg-img-controls '));
  check('a <div> among list items → error doc/list-children', has(swap('</body>', '<ol><li>a</li><div>b</div></ol></body>'), ' error doc/list-children '));
  check('the same SVG as role="group" passes', !has(swap('</body>', '<svg role="group" aria-label="d"><g tabindex="0" role="button" aria-label="x"><rect/></g></svg></body>'), 'doc/svg-img-controls'));
}

console.log('tokens: surface pairs in every theme, label on a fill, large accent face');
{
  const has = (html, rule) => run([write(`t-${Math.random().toString(36).slice(2)}.html`, html)]).out;
  const low = swap('--brand: oklch(0.62 0.12 250); }', '--brand: oklch(0.62 0.12 250); --tint: oklch(0.97 0 0); --tint-ink: oklch(0.6 0 0); }');
  check('--tint-ink under 4.5:1 on --tint → error doc/theme-contrast', / error doc\/theme-contrast .*--tint-ink on --tint/.test(has(low)));
  const dark = swap('[data-theme="dark"] { --background: oklch(0.2 0 0);', '.box { background: var(--tint); } .box .lab { color: var(--ink); } :root { --tint: oklch(0.97 0 0); --ink: oklch(0.3 0 0); } [data-theme="dark"] { --tint: oklch(0.25 0 0); --ink: oklch(0.35 0 0); --background: oklch(0.2 0 0);');
  check('a label color unreadable on its container in the dark theme → warning', / warning doc\/theme-contrast .*--ink on --tint in the dark theme/.test(has(dark)));
  const font = swap('<style>', `<style>@font-face { font-family: "Showy"; src: url(data:font/woff2;base64,${'A'.repeat(70 * 1024)}) format("woff2"); }`);
  check('a 70 KB face no font token names → warning doc/large-font', / warning doc\/large-font /.test(has(font)));
}

console.log('--render: a click that writes words, print in a dark system theme');
{
  const clicky = swap('</body>', '<button type="button" id="b">More</button><p id="out"></p><script>document.getElementById("b").addEventListener("click", function () { document.getElementById("out").textContent = "Added by the script after a click."; });</script></body>');
  const r = run([write('render.html', clicky), '--render']);
  if (/render\/unavailable/.test(r.out)) {
    console.log('  skipped: no browser for --render here');
  } else {
    check('--render: a click that adds words → warning render/text-on-click', / warning render\/text-on-click /.test(r.out), r.out);
    check('--render: the CLEAN page prints dark under a dark system theme → warning render/print-dark', / warning render\/print-dark /.test(r.out), r.out);
    const quiet = run([write('render-clean.html', swap('</style>', '@media print { :root, :root:not([data-theme="light"]):not([data-theme="dark"]) { --background: oklch(0.99 0 0); --foreground: oklch(0.22 0 0); } }</style>')), '--render']);
    const wide = run([write('render-wide.html', swap('</body>', `<p><span style="white-space: nowrap">${'unbreakable '.repeat(40)}</span></p></body>`)), '--render']);
    check('--render: a no-wrap line wider than the phone → error render/horizontal-scroll, exit 2', wide.status === 2 && / error render\/horizontal-scroll /.test(wide.out), wide.out);
    check('--render: a static page with a light print block has no render findings', !/render\//.test(quiet.out), quiet.out);
  }
}

console.log('--json and exit codes');
{
  const bad = write('json-bad.html', swap('<html lang="en">', '<html>'));
  const r = run([bad, '--json']);
  const lines = r.out.trim().split('\n').map((l) => { try { return JSON.parse(l); } catch { return null; } });
  check('every line is JSON', lines.every(Boolean), r.out);
  const finding = lines.find((l) => l && l.rule === 'doc/missing-lang');
  check('finding carries file, line, severity, rule, message', !!finding && finding.file === bad && finding.severity === 'error' && typeof finding.message === 'string' && 'line' in finding, r.out);
  const last = lines[lines.length - 1];
  check('last line is the summary', !!last?.summary && last.summary.error >= 1, r.out);
  check('--json keeps exit 2', r.status === 2);

  const missing = run([join(TMP, 'does-not-exist.html')]);
  check('unreadable file → exit 1', missing.status === 1, missing.out);
  const usage = run([]);
  check('no arguments → exit 1', usage.status === 1, usage.out);
  const flag = run(['--strict', write('clean2.html', CLEAN)]);
  check('unknown flag → exit 1', flag.status === 1, flag.out);
}

if (failures) {
  console.log(`\n${failures} assertion(s) failed.`);
  process.exit(1);
}
console.log('\nall assertions passed.');
